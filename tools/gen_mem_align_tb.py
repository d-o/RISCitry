"""Generate source/tb/mem_align_tb.luc: every load width at every byte offset, every store width
at every byte offset, with data that exposes sign-extension and lane mistakes.

Expected values are computed here from the spec (little-endian, LB/LH sign-extend, LBU/LHU
zero-extend). Misaligned halfword/word offsets are included: mem_align's documented behaviour
is to ignore the low address bits.

Usage: python3 tools/gen_mem_align_tb.py
"""
from pathlib import Path

LOADS = {0b000: ("lb", 1, True), 0b001: ("lh", 2, True), 0b010: ("lw", 4, False),
         0b100: ("lbu", 1, False), 0b101: ("lhu", 2, False)}
STORES = {0b000: ("sb", 1), 0b001: ("sh", 2), 0b010: ("sw", 4)}
WORDS = [0x80817F01, 0x7F80FF00, 0x12345678, 0xFFFFFFFF, 0x00000000]
STORE_DATA = [0x12345678, 0xFFFFFF80, 0x0000007F]


def load_expected(f3, offset, word):
    _, size, signed = LOADS[f3]
    shift = 8 * (offset & ~(size - 1))        # misaligned: low bits ignored
    value = (word >> shift) & ((1 << (8 * size)) - 1)
    if signed and value & (1 << (8 * size - 1)):
        value -= 1 << (8 * size)
    return value & 0xFFFFFFFF


def store_expected(f3, offset, data):
    _, size = STORES[f3]
    lane = offset & ~(size - 1) & 3            # misaligned: low bits ignored
    chunk = data & ((1 << (8 * size)) - 1)
    write_data = int.from_bytes(chunk.to_bytes(size, "little") * (4 // size), "little")
    enable = ((1 << size) - 1) << lane
    return write_data, enable


def main():
    out = [
        "// GENERATED by tools/gen_mem_align_tb.py. Do not edit; rerun the script.",
        "// Every load and store width at every byte offset (misaligned offsets use the aligned",
        "// halfword/word, which is mem_align's documented behaviour).",
        "testbench mem_align_tb {",
        "    sig in_f3[3]",
        "    sig in_addr[2]",
        "    sig in_store[32]",
        "    sig in_word[32]",
        "",
        "    mem_align dut(.funct3(in_f3), .addr_low(in_addr), .store_data(in_store), .load_word(in_word))",
        "",
        "    fun check_load(f3[3], addr[2], word[32], expected[32]) {",
        "        in_f3 = f3",
        "        in_addr = addr",
        "        in_word = word",
        "        $tick()",
        "        if (dut.load_data != expected)",
        '            $print("load f3=%b addr=%d word=%h: got %h want %h", f3, addr, word, dut.load_data, expected)',
        "        $assert(dut.load_data == expected)",
        "    }",
        "",
        "    fun check_store(f3[3], addr[2], data[32], wdata[32], enable[4]) {",
        "        in_f3 = f3",
        "        in_addr = addr",
        "        in_store = data",
        "        $tick()",
        "        if (dut.write_data != wdata || dut.byte_enable != enable)",
        '            $print("store f3=%b addr=%d data=%h: got %h/%b want %h/%b", f3, addr, data, dut.write_data, dut.byte_enable, wdata, enable)',
        "        $assert(dut.write_data == wdata)",
        "        $assert(dut.byte_enable == enable)",
        "    }",
        "",
        "    test loads {",
        "        in_f3 = 0", "        in_addr = 0", "        in_store = 0", "        in_word = 0",
    ]
    count = 0
    for f3, (name, _, _) in LOADS.items():
        for word in WORDS:
            for offset in range(4):
                exp = load_expected(f3, offset, word)
                out.append(f"        $check_load(3b{f3:03b}, 2d{offset}, 32h{word:08X}, 32h{exp:08X}) // {name} +{offset}")
                count += 1
    out += ["    }", "", "    test stores {",
            "        in_f3 = 0", "        in_addr = 0", "        in_store = 0", "        in_word = 0"]
    for f3, (name, _) in STORES.items():
        for data in STORE_DATA:
            for offset in range(4):
                wdata, enable = store_expected(f3, offset, data)
                out.append(f"        $check_store(3b{f3:03b}, 2d{offset}, 32h{data:08X}, 32h{wdata:08X}, "
                           f"4b{enable:04b}) // {name} +{offset}")
                count += 1
    out += ["    }", "}"]
    dest = Path(__file__).resolve().parent.parent / "source" / "tb" / "mem_align_tb.luc"
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest} ({count} checks)")


if __name__ == "__main__":
    main()
