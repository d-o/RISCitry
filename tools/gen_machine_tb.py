"""Generate source/tb/machine_tb.luc: the run/step clock sequencer around the cpu.

Runs the MEMORY program (2-, 3- and 4-clock instructions) on the machine with short clock
periods, checked against tools/rv32sim.py:
  - after reset, with run off, the machine is stopped at pc 0 (state FETCH)
  - the cpu clock light toggles once per cpu clock (checked while stepping, where the count is known)
  - clock mode: each step pulse is one cpu clock (state and pc checked after each, through an
    ALU op, a store and a load)
  - a clock step part-way into an instruction, then instruction mode: it stays put until a step,
    which finishes that instruction
  - instruction mode: each step pulse runs exactly one instruction and stops again (checked after
    far more clocks than the instruction needs, so an overrun shows)
  - a step pulse while running is ignored, and the stopped light stays off while running
  - run on, then off, stops between instructions; the program ends at its halt loop
  - reset while stopped restarts at pc 0 without needing run or a step; then a fast run

Usage: python3 tools/gen_machine_tb.py
"""
from pathlib import Path

import asm
import programs
import rv32sim
from gen_cpu_tb import STATES, clocks_for, writes_rd

ROOT = Path(__file__).resolve().parent.parent
PROGRAM = "MEMORY"
SLOW_BITS, FAST_BITS = 3, 1
SETTLE = 64                 # clocks after a step: a 4-clock instruction needs 4 * 2^FAST_BITS


def main():
    words, text = asm.assemble_with_listing(programs.PROGRAMS[PROGRAM])
    model = rv32sim.Cpu(words)
    out = [
        "// GENERATED by tools/gen_machine_tb.py, checked against tools/rv32sim.py. Do not edit; rerun the script.",
        f"// The run/step clock sequencer: steps the {PROGRAM} program by clock and by instruction,",
        "// then run/stop and reset.",
        "testbench machine_tb {",
        "    sig clk",
        "    sig rst",
        "    sig run",
        "    sig fast",
        "    sig clock_step",
        "    sig step",
        "    sig sel[4]",
        "    sig switches[8]",
        "    sig buttons[4]",
        "",
        f"    machine dut(#PROGRAM_ID(Programs.Id.{PROGRAM}), #SIM_RAM(1), #SLOW_BITS({SLOW_BITS}), #FAST_BITS({FAST_BITS}),",
        "                .clk(clk), .rst(rst), .run(run), .fast(fast), .clock_step(clock_step), .step(step),",
        "                .switches(switches), .buttons(buttons), .debug_sel(sel))",
        "",
        "    fun tick_clock() {",
        "        clk = 1",
        "        $silent_tick()",
        "        clk = 0",
        "        $silent_tick()",   # silent: every $tick() keeps a whole-design snapshot (RAM model included)
        "    }",
        "",
        "    fun settle() {",
        f"        repeat(i, {SETTLE}) {{ $tick_clock(); }}",
        "    }",
        "",
        "    // a step pulse, then wait (busy while the step is under way)",
        "    fun press_step() {",
        "        step = 1",
        "        $tick_clock()",
        "        step = 0",
        "        $tick_clock()",
        "        $assert(dut.busy)",
        "        $settle()",
        "    }",
        "",
        "    fun expect_stopped_at(pc[32], state[Cpu.STATE_BITS]) {",
        "        if (dut.debug_pc != pc || dut.cpu_state != state || !dut.halted)",
        '            $print("pc: got %h want %h, state %d want %d, halted %b", dut.debug_pc, pc, dut.cpu_state, state, dut.halted)',
        "        $assert(dut.debug_pc == pc)",
        "        $assert(dut.cpu_state == state)",
        "        $assert(dut.halted)",
        "        $assert(!dut.busy)",
        "        $assert(dut.uart_tx)       // MEMORY doesn't print: serial line idle high",
        "        $assert(!dut.display_owned && dut.display_chars == 0)   // nor use the display",
        "    }",
        "",
        "    fun expect_reg(r[4], value[32]) {",
        "        sel = r",
        "        $silent_tick()",
        "        if (dut.debug_reg != value)",
        '            $print("x%d: got %h want %h", r, dut.debug_reg, value)',
        "        $assert(dut.debug_reg == value)",
        "    }",
        "",
        "    test step_run_reset {",
        "        clk = 0",
        "        rst = 1",
        "        run = 0",
        "        fast = 0",
        "        clock_step = 0",
        "        step = 0",
        "        sel = 0",
        "        switches = 0",
        "        buttons = 0",
        "        $tick_clock()",
        "        $tick_clock()",
        "        $assert(dut.in_reset)",
        "        rst = 0",
        "        $settle()",
        "        $assert(!dut.in_reset)",
        "        $expect_stopped_at(32h00000000, Cpu.State.FETCH)",
        "        $settle()",
        "        $expect_stopped_at(32h00000000, Cpu.State.FETCH)   // stays stopped",
        "        $assert(dut.cpu_clock == 0)   // two cpu clocks in reset: toggled twice",
    ]

    led = [0]                # the cpu clock light: reset gives two cpu clocks, so it's back at 0

    def toggle(n=1):
        led[0] ^= n & 1
        out.append(f"        $assert(dut.cpu_clock == {led[0]})")

    def next_instruction():
        pc = model.pc
        word = model.fetch()
        model.step()
        return pc, word

    def expect_rd(word):
        rd = writes_rd(word)
        if rd is not None:
            out.append(f"        $expect_reg(4d{rd}, 32h{model.x[rd]:08X})")

    def clock_steps(count):
        """Clock-step whole instructions: state and pc after every cpu clock."""
        out.append("        clock_step = 1")
        for _ in range(count):
            pc, word = next_instruction()
            out.append(f"        // clock steps: {pc:#06x}: {text.get(pc, 'nop')}")
            for state in STATES[clocks_for(word)]:
                now = model.pc if state == "FETCH" else pc
                out.extend(["        $press_step()", f"        $expect_stopped_at(32h{now:08X}, Cpu.State.{state})"])
                toggle()
            expect_rd(word)

    def instruction_steps(count):
        out.append("        clock_step = 0")
        for _ in range(count):
            pc, word = next_instruction()
            out.extend([f"        // step: {pc:#06x}: {text.get(pc, 'nop')}", "        $press_step()",
                        f"        $expect_stopped_at(32h{model.pc:08X}, Cpu.State.FETCH)"])
            toggle(clocks_for(word))
            expect_rd(word)

    clock_steps(1)
    # one clock into the next instruction, then instruction mode: no movement until a step
    pc, word = next_instruction()
    out += [f"        // one clock step into {pc:#06x}: {text.get(pc, 'nop')}, then instruction mode",
            "        clock_step = 1",
            "        $press_step()",
            f"        $expect_stopped_at(32h{pc:08X}, Cpu.State.EXECUTE)",
            f"        $assert(dut.cpu_clock == {led[0] ^ 1})",
            "        clock_step = 0",
            "        $settle()",
            f"        $expect_stopped_at(32h{pc:08X}, Cpu.State.EXECUTE)",
            "        $press_step()",
            f"        $expect_stopped_at(32h{model.pc:08X}, Cpu.State.FETCH)"]
    toggle(clocks_for(word))         # one clock step plus the rest of the instruction
    expect_rd(word)
    instruction_steps(5)             # through sw (3 clocks) and lw (4 clocks)
    clock_steps(3)                   # add, then sw and lw clock by clock
    assert [clocks_for(words[a]) for a in (model.pc - 12, model.pc - 8, model.pc - 4)] == [2, 3, 4]

    out += [
        "        // run, with a step pulse that must be ignored, then stop: ends in the halt loop",
        "        clock_step = 0",
        "        run = 1",
        "        $tick_clock()",
        "        step = 1",
        "        $tick_clock()",
        "        step = 0",
        "        repeat(i, 64) {",
        "            $tick_clock()",
        "            $assert(!dut.halted)    // the stopped light stays off while running",
        "        }",
        "        repeat(i, 40) { $settle(); }",
        "        run = 0",
        "        $settle()",
    ]
    while model.fetch() != asm.HALT:
        model.step()
    out.append(f"        $expect_stopped_at(32h{model.pc:08X}, Cpu.State.FETCH)")
    out += [f"        $expect_reg(4d{r}, 32h{model.x[r]:08X})" for r in range(16)]
    out += [
        "        // reset while stopped",
        "        rst = 1",
        "        $tick_clock()",
        "        rst = 0",
        "        $settle()",
        "        $expect_stopped_at(32h00000000, Cpu.State.FETCH)",
        "        $assert(dut.cpu_clock == 0)",
        "        $expect_reg(4d2, 32h00000000)",
        "        // fast run reaches the halt loop too",
        "        fast = 1",
        "        run = 1",
        "        repeat(i, 10) { $settle(); }",
        "        run = 0",
        "        $settle()",
        f"        $expect_stopped_at(32h{model.pc:08X}, Cpu.State.FETCH)",
        f"        $expect_reg(4d10, 32h{model.x[10]:08X})",
        "    }",
        "}",
    ]
    dest = ROOT / "source" / "tb" / "machine_tb.luc"
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest}")


SLEEP_PROGRAM = "WFI"
SLEEP_TICK_DIV = 4          # mtime ticks every 4 clocks, so a 60-tick wait (~240 clocks) outlasts the checks


def sleep_main():
    """machine_sleep_tb: while the cpu waits in a WFI and run is on, the machine stops giving it
    clock pulses (the cpu-clock light freezes), and wakes it on the interrupt: first the timer
    (slow), then a button press (fast)."""
    words, text = asm.assemble_with_listing(programs.PROGRAMS[SLEEP_PROGRAM])
    wfi = sorted(a for a, w in words.items() if w == 0x10500073)
    assert len(wfi) == 3, wfi
    halt = max(a for a, w in words.items() if w == asm.HALT)
    # what the handler leaves: it runs for (a) and (c); mepc = WFI + 4 each time
    sum_mepc = (wfi[0] + 4) + (wfi[2] + 4)
    out = [
        "// GENERATED by tools/gen_machine_tb.py. Do not edit; rerun the script.",
        f"// Sleep in WFI: running the {SLEEP_PROGRAM} program, the machine stops pulsing the cpu clock while a WFI",
        "// waits (the light freezes, state and pc stay), and the timer / a button press wake it.",
        "testbench machine_sleep_tb {",
        "    sig clk",
        "    sig rst",
        "    sig run",
        "    sig fast",
        "    sig clock_step",
        "    sig step",
        "    sig sel[4]",
        "    sig switches[8]",
        "    sig buttons[4]",
        "    sig found",
        "    sig light",
        "",
        f"    machine dut(#PROGRAM_ID(Programs.Id.{SLEEP_PROGRAM}), #SIM_RAM(1), #SLOW_BITS({SLOW_BITS}), "
        f"#FAST_BITS({FAST_BITS}), #TICK_DIV({SLEEP_TICK_DIV}),",
        "                .clk(clk), .rst(rst), .run(run), .fast(fast), .clock_step(clock_step), .step(step),",
        "                .switches(switches), .buttons(buttons), .debug_sel(sel))",
        "",
        "    fun tick_clock() {",
        "        clk = 1",
        "        $silent_tick()",
        "        clk = 0",
        "        $silent_tick()",
        "    }",
        "",
        "    // run until the cpu sits in EXECUTE at pc (a WFI), at most 800 clocks",
        "    fun wait_at(pc[32]) {",
        "        found = 0",
        "        repeat(i, 800) {",
        "            if (!found) {",
        "                $tick_clock()",
        "                if (dut.debug_pc == pc && dut.cpu_state == Cpu.State.EXECUTE) found = 1",
        "            }",
        "        }",
        "        $assert(found)",
        "    }",
        "",
        "    // asleep: for 80 clocks (ten slow cpu clocks) the light, pc and state don't move",
        "    fun expect_asleep(pc[32]) {",
        "        light = dut.cpu_clock",
        "        $assert(!dut.halted && !dut.busy && !dut.in_reset)   // running, not in reset",
        "        $assert(dut.uart_tx && !dut.display_owned && dut.display_chars == 0)   // WFI prints nothing",
        "        repeat(i, 80) {",
        "            $tick_clock()",
        "            $assert(dut.cpu_clock == light)",
        "            $assert(dut.debug_pc == pc)",
        "            $assert(dut.cpu_state == Cpu.State.EXECUTE)",
        "        }",
        "    }",
        "",
        "    // woken: the pc leaves the WFI within 400 clocks",
        "    fun wait_wake(pc[32]) {",
        "        found = 0",
        "        repeat(i, 400) {",
        "            if (!found) {",
        "                $tick_clock()",
        "                if (dut.debug_pc != pc) found = 1",
        "            }",
        "        }",
        "        $assert(found)",
        "    }",
        "",
        "    fun expect_reg(r[4], value[32]) {",
        "        sel = r",
        "        $silent_tick()",
        "        if (dut.debug_reg != value)",
        '            $print("x%d: got %h want %h", r, dut.debug_reg, value)',
        "        $assert(dut.debug_reg == value)",
        "    }",
        "",
        "    test sleep {",
        "        clk = 0",
        "        rst = 1",
        "        run = 0",
        "        fast = 0",
        "        clock_step = 0",
        "        step = 0",
        "        sel = 0",
        "        switches = 0",
        "        buttons = 0",
        "        found = 0",
        "        light = 0",
        "        $tick_clock()",
        "        $tick_clock()",
        "        rst = 0",
        "        repeat(i, 64) { $tick_clock(); }",
        "        // (a) the timer wakes a WFI, run slow",
        "        run = 1",
        f"        $wait_at(32h{wfi[0]:08X})",
        "        $tick_clock()",
        "        $tick_clock()",
        f"        $expect_asleep(32h{wfi[0]:08X})",
        f"        $wait_wake(32h{wfi[0]:08X})",
        "        // (b) MIE = 0: the timer wakes it and it completes",
        f"        $wait_at(32h{wfi[1]:08X})",
        "        $tick_clock()",
        "        $tick_clock()",
        f"        $expect_asleep(32h{wfi[1]:08X})",
        f"        $wait_wake(32h{wfi[1]:08X})",
        "        // (c) run fast: nothing to wake it but a press",
        "        fast = 1",
        f"        $wait_at(32h{wfi[2]:08X})",
        "        $tick_clock()",
        "        $tick_clock()",
        f"        $expect_asleep(32h{wfi[2]:08X})",
        "        buttons = 4h1",
        "        repeat(i, 4) { $tick_clock(); }",
        "        buttons = 4h0",
        f"        $wait_wake(32h{wfi[2]:08X})",
        "        repeat(i, 200) { $tick_clock(); }",
        "        run = 0",
        "        repeat(i, 64) { $tick_clock(); }",
        f"        $assert(dut.halted && dut.debug_pc == 32h{halt:08X})",
        "        $expect_reg(4d14, 32h00000002)         // handler ran twice: (a) and (c)",
        f"        $expect_reg(4d10, 32h{sum_mepc:08X})   // mepc = WFI + 4 each time",
        "        $expect_reg(4d13, 32h8000000B)         // the last: external interrupt",
        "    }",
        "}",
    ]
    dest = ROOT / "source" / "tb" / "machine_sleep_tb.luc"
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
    sleep_main()
