"""Generate source/machine_tb.luc: the run/step clock sequencer around the cpu.

Runs the MEMORY program (2-, 3- and 4-clock instructions) on the machine with short clock
periods:
  - after reset, with run off, the machine is stopped at pc 0
  - each step pulse runs exactly one instruction and stops again (pc and rd checked against
    tools/rv32sim.py, after far more clocks than the instruction needs, so an overrun shows)
  - a step pulse while running is ignored
  - run on, then off, stops between instructions; the program ends at its halt loop
  - reset while stopped restarts at pc 0 without needing run or a step

Usage: python3 tools/gen_machine_tb.py
"""
from pathlib import Path

import asm
import programs
import rv32sim

ROOT = Path(__file__).resolve().parent.parent
PROGRAM = "MEMORY"
SLOW_BITS, FAST_BITS = 3, 1
SETTLE = 64                 # fast clocks after a step: a 4-clock instruction needs 4 * 2 * 2^FAST_BITS
WRITES_RD = {0x37, 0x17, 0x6F, 0x67, 0x03, 0x13, 0x33}


def main():
    words, text = asm.assemble_with_listing(programs.PROGRAMS[PROGRAM])
    model = rv32sim.Cpu(words)
    out = [
        "// GENERATED by tools/gen_machine_tb.py, checked against tools/rv32sim.py. Do not edit; rerun the script.",
        f"// The run/step clock sequencer: single-steps the {PROGRAM} program, then run/stop and reset.",
        "testbench machine_tb {",
        "    sig clk",
        "    sig rst",
        "    sig run",
        "    sig fast",
        "    sig step",
        "    sig sel[4]",
        "",
        f"    machine dut(#PROGRAM_ID(Programs.Id.{PROGRAM}), #SIM_RAM(1), #SLOW_BITS({SLOW_BITS}), #FAST_BITS({FAST_BITS}),",
        "                .clk(clk), .rst(rst), .run(run), .fast(fast), .step(step), .debug_sel(sel))",
        "",
        "    fun tick_clock() {",
        "        clk = 1",
        "        $silent_tick()",
        "        clk = 0",
        "        $tick()",
        "    }",
        "",
        "    fun settle() {",
        f"        repeat(i, {SETTLE}) {{ $tick_clock(); }}",
        "    }",
        "",
        "    fun expect_stopped_at(pc[32]) {",
        "        if (dut.debug_pc != pc || !dut.halted)",
        '            $print("pc: got %h want %h, halted %b", dut.debug_pc, pc, dut.halted)',
        "        $assert(dut.debug_pc == pc)",
        "        $assert(dut.halted)",
        "    }",
        "",
        "    fun expect_reg(r[4], value[32]) {",
        "        sel = r",
        "        $silent_tick()",
        "        if (dut.debug_reg != value)",
        '            $print("x%d: got %h want %h", r, dut.debug_reg, value)',
        "        $assert(dut.debug_reg == value)",
        "    }",
        "",
        "    test step_run_reset {",
        "        clk = 0",
        "        rst = 1",
        "        run = 0",
        "        fast = 0",
        "        step = 0",
        "        sel = 0",
        "        $tick_clock()",
        "        $tick_clock()",
        "        rst = 0",
        "        $settle()",
        "        $expect_stopped_at(32h00000000)",
        "        $settle()",
        "        $expect_stopped_at(32h00000000)   // stays stopped",
    ]
    steps = 0
    while True:
        pc = model.pc
        word = words.get(pc, asm.NOP)
        model.step()
        steps += 1
        out += [f"        // step: {pc:#06x}: {text.get(pc, 'nop')}",
                "        step = 1",
                "        $tick_clock()",
                "        step = 0",
                "        $settle()",
                f"        $expect_stopped_at(32h{model.pc:08X})"]
        if word & 0x7F in WRITES_RD:
            rd = (word >> 7) & 31
            out.append(f"        $expect_reg(4d{rd}, 32h{model.x[rd]:08X})")
        if steps == 7:              # through the first sw (3 clocks) and lw (4 clocks)
            break
    out += [
        "        // run, with a step pulse that must be ignored, then stop: ends in the halt loop",
        "        run = 1",
        "        $tick_clock()",
        "        step = 1",
        "        $tick_clock()",
        "        step = 0",
        "        repeat(i, 64) {",
        "            $tick_clock()",
        "            $assert(!dut.halted)    // the stopped light stays off while running",
        "        }",
        "        repeat(i, 40) { $settle(); }",
        "        run = 0",
        "        $settle()",
    ]
    while words.get(model.pc, asm.NOP) != asm.HALT:
        model.step()
    out.append(f"        $expect_stopped_at(32h{model.pc:08X})")
    out += [f"        $expect_reg(4d{r}, 32h{model.x[r]:08X})" for r in range(16)]
    out += [
        "        // reset while stopped",
        "        rst = 1",
        "        $tick_clock()",
        "        rst = 0",
        "        $settle()",
        "        $expect_stopped_at(32h00000000)",
        "        $expect_reg(4d2, 32h00000000)",
        "        // fast run reaches the halt loop too",
        "        fast = 1",
        "        run = 1",
        "        repeat(i, 10) { $settle(); }",
        "        run = 0",
        "        $settle()",
        f"        $expect_stopped_at(32h{model.pc:08X})",
        f"        $expect_reg(4d10, 32h{model.x[10]:08X})",
        "    }",
        "}",
    ]
    dest = ROOT / "source" / "machine_tb.luc"
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
