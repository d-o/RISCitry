"""The memory map: the one place addresses are defined.

computer.luc decodes these (through source/computer/memory_map.luc, generated from this file by
gen_cpu_tb.py), rv32sim.py models them, and programs.py uses them. One address space for code and
data (von Neumann): the program is preloaded into RAM from address 0 and runs from there, so
data must live clear of the code.

Decoding is full: every byte address outside these ranges is unmapped. The hardware ignores
writes there and reads 0; rv32sim raises, so programs can't depend on either.
"""
RAM_BASE = 0x0000_0000
RAM_BYTES = 8192              # 2048 words: 16 BRAMs (main_ram), code + data

UART_BASE = 0x8000_0000       # 8-byte window
UART_TXDATA = UART_BASE + 0   # write: send byte lane 0 (bits 7:0); dropped if STATUS.busy
UART_STATUS = UART_BASE + 4   # read: bit 0 = busy (a byte is still waiting to be taken)
UART_BYTES = 8

SWITCHES_BASE = 0x8000_1000   # read: bits 7:0 = the board's middle DIP bank (the boot menu's choice)
SWITCHES_BYTES = 4

TIMER_BASE = 0x8000_2000      # machine timer (64-bit registers, word access only)
TIMER_MTIME = TIMER_BASE + 0  # mtime low word; +4 high word. Counts cpu clocks (see timer.luc)
TIMER_MTIMEH = TIMER_BASE + 4
TIMER_MTIMECMP = TIMER_BASE + 8   # mtimecmp low word; +12 high word. MTIP = mtime >= mtimecmp
TIMER_MTIMECMPH = TIMER_BASE + 12
TIMER_BYTES = 16

BUTTONS_BASE = 0x8000_3000    # read: pending [3:0], overrun [7:4], levels [11:8]; write: 1s clear [7:0]
BUTTONS_BYTES = 4             # bit order: up, down, left, right (the Io's direction buttons)

DISPLAY_BASE = 0x8000_4000    # the 7-segment display: four characters, byte k = digit k from the left
DISPLAY_BYTES = 4             # (any store size; read back the same). The board has the font and scans


def render_luc():
    ram_bits = (RAM_BYTES - 1).bit_length()
    assert RAM_BYTES == 1 << ram_bits and RAM_BASE % RAM_BYTES == 0
    assert UART_BASE % UART_BYTES == 0 and SWITCHES_BASE % SWITCHES_BYTES == 0
    assert TIMER_BASE % TIMER_BYTES == 0 and BUTTONS_BASE % BUTTONS_BYTES == 0
    assert DISPLAY_BASE % DISPLAY_BYTES == 0
    return "\n".join([
        "// GENERATED by tools/gen_cpu_tb.py from tools/memmap.py. Do not edit; rerun the script.",
        "// The memory map (byte addresses; code and data share it); computer.luc decodes it.",
        "global MemMap {",
        f"    const RAM_BASE = 32h{RAM_BASE:08X}",
        f"    const RAM_ADDR_BITS = {ram_bits}       // byte address bits inside the RAM",
        f"    const RAM_WORDS = {RAM_BYTES // 4}",
        f"    const UART_BASE = 32h{UART_BASE:08X}    // TXDATA at +0, STATUS at +4",
        "    const UART_ADDR_BITS = 3",
        f"    const SWITCHES_BASE = 32h{SWITCHES_BASE:08X}    // bits 7:0 = switches",
        "    const SWITCHES_ADDR_BITS = 2",
        f"    const TIMER_BASE = 32h{TIMER_BASE:08X}    // mtime +0/+4, mtimecmp +8/+12",
        "    const TIMER_ADDR_BITS = 4",
        f"    const BUTTONS_BASE = 32h{BUTTONS_BASE:08X}    // pending [3:0], overrun [7:4], levels [11:8]; write 1s to clear",
        "    const BUTTONS_ADDR_BITS = 2",
        f"    const DISPLAY_BASE = 32h{DISPLAY_BASE:08X}    // four characters, byte k = digit k from the left",
        "    const DISPLAY_ADDR_BITS = 2",
        "}",
    ]) + "\n"
