"""Generate source/tb/imm_gen_tb.luc from rv32.py, so expected immediates never come from hand-encoding.

Each immediate is encoded twice: once with every non-immediate field all ones (rd/rs1/rs2 = x31,
funct3 = 7) to catch bits leaking in from neighbouring fields, and once with those fields zero.
imm_type is driven the way the decoder would drive it.

Usage: python3 tools/gen_imm_gen_tb.py   (rewrites source/tb/imm_gen_tb.luc)
"""
from pathlib import Path

import rv32

I_IMMS = [0, 1, -1, 2047, -2048, 0x555, -0x556, 0x7C]
B_IMMS = [0, 2, -2, 4094, -4096, 0x800, -0x800, 0xAAA, -0x556, -0x34]
J_IMMS = [0, 2, -2, 0xFFFFE, -0x100000, 0x800, 0x55554, -0x2AAAC, 0x7C, -0x34]


# Mirrors enum Cpu.ImmType in source/cpu/cpu_defs.luc.
IMM_TYPE = {"I": 0, "S": 1, "B": 2, "U": 3, "J": 4}
U_IMMS = [0, 1, 0x80000, 0xFFFFF, 0x12345, 0x7FFFF]


def vectors():
    """(word, imm_type, expected immediate as a 32-bit pattern, note) grouped by format."""
    groups = {}
    for f3, reg in ((7, 31), (0, 0)):
        tag = "fields=1" if reg else "fields=0"
        groups.setdefault("i_type", []).extend(
            (rv32.i_type(op, reg, f3, reg, imm), "I", imm, f"{name} imm={imm} {tag}")
            for op, name in ((0x13, "op-imm"), (0x03, "load"), (0x67, "jalr")) for imm in I_IMMS)
        groups.setdefault("s_type", []).extend(
            (rv32.s_type(0x23, f3, reg, reg, imm), "S", imm, f"store imm={imm} {tag}") for imm in I_IMMS)
        groups.setdefault("b_type", []).extend(
            (rv32.b_type(0x63, f3, reg, reg, imm), "B", imm, f"branch imm={imm} {tag}") for imm in B_IMMS)
        groups.setdefault("u_type", []).extend(
            (rv32.u_type(op, reg, imm), "U", imm << 12, f"{name} imm={imm:#x} {tag}")
            for op, name in ((0x37, "lui"), (0x17, "auipc")) for imm in U_IMMS)
        groups.setdefault("j_type", []).extend(
            (rv32.j_type(0x6F, reg, imm), "J", imm, f"jal imm={imm} {tag}") for imm in J_IMMS)
    for word, _, imm, _ in (v for g in groups.values() for v in g):
        assert rv32.u32(rv32.decode_imm(word)) == rv32.u32(imm), f"{word:08X}"
    return groups


def render(groups):
    out = [
        "// GENERATED by tools/gen_imm_gen_tb.py from tools/rv32.py. Do not edit; rerun the script.",
        "// Checks imm_gen's immediate for I, S, B, U and J formats (imm_type driven as the decoder would).",
        "testbench imm_gen_tb {",
        "    sig in_inst[32]",
        "    sig in_type[3]",
        "",
        "    imm_gen dut(.instruction(in_inst), .imm_type(in_type))",
        "",
        "    fun check(inst[32], imm_type[3], expected[32]) {",
        "        in_inst = inst",
        "        in_type = imm_type",
        "        $tick()",
        "        if (dut.immediate != expected)",
        '            $print("inst=%h got=%h want=%h", inst, dut.immediate, expected)',
        "        $assert(dut.immediate == expected)",
        "    }",
    ]
    for name, vecs in groups.items():
        out += ["", f"    test {name} {{", "        in_inst = 0", "        in_type = 0"]
        out += [f"        $check(32h{word:08X}, 3d{IMM_TYPE[t]}, 32h{rv32.u32(imm):08X}) // {note}"
                for word, t, imm, note in vecs]
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    dest = Path(__file__).resolve().parent.parent / "source" / "tb" / "imm_gen_tb.luc"
    groups = vectors()
    dest.write_text(render(groups))
    print(f"wrote {dest} ({sum(len(v) for v in groups.values())} checks)")
