"""Generate source/imm_gen_tb.luc from rv32.py, so expected immediates never come from hand-encoding.

Each immediate is encoded twice: once with every non-immediate field all ones (rd/rs1/rs2 = x31,
funct3 = 7) to catch bits leaking in from neighbouring fields, and once with those fields zero.

Usage: python3 tools/gen_imm_gen_tb.py   (rewrites source/imm_gen_tb.luc)
"""
from pathlib import Path

import rv32

I_IMMS = [0, 1, -1, 2047, -2048, 0x555, -0x556, 0x7C]
B_IMMS = [0, 2, -2, 4094, -4096, 0x800, -0x800, 0xAAA, -0x556, -0x34]
J_IMMS = [0, 2, -2, 0xFFFFE, -0x100000, 0x800, 0x55554, -0x2AAAC, 0x7C, -0x34]


def vectors():
    groups = {}
    for f3, reg in ((7, 31), (0, 0)):
        tag = "fields=1" if reg else "fields=0"
        groups.setdefault("i_type", []).extend(
            (rv32.i_type(op, reg, f3, reg, imm), imm, f"{name} imm={imm} {tag}")
            for op, name in ((0x13, "op-imm"), (0x03, "load")) for imm in I_IMMS)
        groups.setdefault("s_type", []).extend(
            (rv32.s_type(0x23, f3, reg, reg, imm), imm, f"store imm={imm} {tag}") for imm in I_IMMS)
        groups.setdefault("b_type", []).extend(
            (rv32.b_type(0x63, f3, reg, reg, imm), imm, f"branch imm={imm} {tag}") for imm in B_IMMS)
        groups.setdefault("j_type", []).extend(
            (rv32.j_type(0x6F, reg, imm), imm, f"jal imm={imm} {tag}") for imm in J_IMMS)
    # Formats imm_gen doesn't produce an immediate for (yet) must give 0.
    groups["no_imm"] = [
        (rv32.add(31, 31, 31), 0, "R-type add has no immediate"),
        (0xFFFFFFB3, 0, "R-type, all other bits set"),
    ]
    for word, imm, _ in (v for g in groups.values() for v in g):
        if word & 0x7F != 0x33:
            assert rv32.decode_imm(word) == imm, f"{word:08X}"
    return groups


def render(groups):
    out = [
        "// GENERATED by tools/gen_imm_gen_tb.py from tools/rv32.py. Do not edit; rerun the script.",
        "// Checks imm_gen's sign-extended immediate for I, S, B and J formats.",
        "// Not covered yet: U-type (LUI/AUIPC) and JALR, which imm_gen doesn't implement.",
        "testbench imm_gen_tb {",
        "    sig in_inst[32]",
        "    sig in_op[7]",
        "",
        "    imm_gen dut(.instruction(in_inst), .opcode(in_op))",
        "",
        "    fun check(inst[32], expected[32]) {",
        "        in_inst = inst",
        "        in_op = inst[6:0]",
        "        $tick()",
        "        if (dut.immediate != expected)",
        '            $print("inst=%h got=%h want=%h", inst, dut.immediate, expected)',
        "        $assert(dut.immediate == expected)",
        "    }",
    ]
    for name, vecs in groups.items():
        out += ["", f"    test {name} {{", "        in_inst = 0", "        in_op = 0"]
        out += [f"        $check(32h{word:08X}, 32h{rv32.u32(imm):08X}) // {note}" for word, imm, note in vecs]
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    dest = Path(__file__).resolve().parent.parent / "source" / "imm_gen_tb.luc"
    groups = vectors()
    dest.write_text(render(groups))
    print(f"wrote {dest} ({sum(len(v) for v in groups.values())} checks)")
