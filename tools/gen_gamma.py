"""Write c/gamma.h: the fader's gamma table, gamma_lut[level] = round(255 * (level / 255) ** 2.2).

Linear levels (a decay by shifting) look wrong on LEDs because the eye's response is roughly a
power law: without this table the tail of the fading scanner looks like four nearly equal LEDs.
The small levels map to 0, which also ends the tail cleanly. Run: python3 tools/gen_gamma.py
(the output is committed, so building the C programs needs only the compiler).
"""
from pathlib import Path

GAMMA = 2.2
OUT = Path(__file__).resolve().parent.parent / "c" / "gamma.h"


def table():
    return [round(255 * (i / 255) ** GAMMA) for i in range(256)]


def render():
    rows = [", ".join(f"{v:3d}" for v in table()[i:i + 16]) for i in range(0, 256, 16)]
    return "\n".join([
        "/* GENERATED by tools/gen_gamma.py. Do not edit; rerun the script. */",
        "#ifndef GAMMA_H",
        "#define GAMMA_H",
        f"/* gamma_lut[level] = round(255 * (level / 255) ** {GAMMA}): linear level -> perceived brightness */",
        "static const unsigned char gamma_lut[256] = {",
        *[f"    {row}," for row in rows],
        "};",
        "#endif",
        "",
    ])


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT}")
