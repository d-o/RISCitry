"""Generate source/cpu_tb.luc: run the ROM in instruction_mem.luc on the Python model
(tools/rv32sim.py) and check the cpu core's pc and x1 after every instruction.

The core is multi-cycle (FETCH + EXECUTE), so each check is exactly 2 clocks after the last.
A slower instruction (an extra cycle, a double beat) shows up as a pc/x1 mismatch.

Usage: python3 tools/gen_cpu_tb.py [instructions]   (default 34: boot + two full sweeps)
"""
import sys
from pathlib import Path

import rv32sim

ROOT = Path(__file__).resolve().parent.parent
CLOCKS_PER_INSTRUCTION = 2


def main(count):
    rom, default_word = rv32sim.load_rom(ROOT / "source" / "instruction_mem.luc")
    model = rv32sim.Cpu(rom, default_word)
    lines = [
        "// GENERATED by tools/gen_cpu_tb.py from the ROM in instruction_mem.luc, run on tools/rv32sim.py.",
        "// Do not edit; rerun the script after changing the ROM.",
        f"// Checks pc and x1 after each of {count} instructions, {CLOCKS_PER_INSTRUCTION} clocks apart.",
        "testbench cpu_tb {",
        "    sig clk",
        "    sig rst",
        "",
        "    cpu dut(.clk(clk), .rst(rst))",
        "",
        "    fun tick_clock() {",
        "        clk = 1",
        "        $silent_tick()",
        "        clk = 0",
        "        $tick()",
        "    }",
        "",
        "    fun step(pc[32], x1[32]) {",
        *[f"        $tick_clock()" for _ in range(CLOCKS_PER_INSTRUCTION)],
        "        if (dut.debug_pc != pc || dut.debug_x1 != x1)",
        '            $print("got pc=%h x1=%h, want pc=%h x1=%h", dut.debug_pc, dut.debug_x1, pc, x1)',
        "        $assert(dut.debug_pc == pc)",
        "        $assert(dut.debug_x1 == x1)",
        "    }",
        "",
        "    test larson {",
        "        clk = 0",
        "        rst = 1",
        "        $tick_clock()",
        "        $tick_clock()",
        "        rst = 0",
        "        $assert(dut.debug_pc == 0)",
    ]
    for _ in range(count):
        word = rom.get(model.pc, default_word)
        pc_before = model.pc
        model.step()
        lines.append(f"        $step(32h{model.pc:08X}, 32h{model.x[1]:08X}) "
                     f"// {pc_before:#06x}: {word:08X} -> led {model.x[1] & 0xFF:08b}")
    lines += ["    }", "}"]
    dest = ROOT / "source" / "cpu_tb.luc"
    dest.write_text("\n".join(lines) + "\n")
    print(f"wrote {dest} ({count} instruction checks)")


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 34)
