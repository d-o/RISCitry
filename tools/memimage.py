"""Initial memory contents for main_ram, in both of its implementations.

main_ram_bram.v (hardware): the program in an `initial` block, which Yosys turns into initialised
block RAM. program_image.luc (simulation): the same words as a combinational lookup, which
main_ram's Lucid model overlays its writes on. The Alchitry simulator doesn't run Verilog, so
tools/check_main_ram.py reads the Verilog back through Yosys and compares it with the programs.

Words past the end of a program are 0, like an uninitialised iCE40 block RAM (0 decodes as an
illegal instruction).
"""
import asm

HEADER = "GENERATED by tools/gen_cpu_tb.py (tools/memimage.py) from tools/programs.py. Do not edit; rerun the script."


def image(words):
    """The program as a list of words from address 0 (gaps are nops, as assembled)."""
    return asm.to_list(words)


def render_program_image(assembled):
    out = [f"// {HEADER}",
           "// A program's initial memory image for main_ram's simulation model: word-addressed,",
           "// combinational, 0 past the end of the program. PROGRAM_ID is a Programs.Id.",
           "module program_image #(",
           "    PROGRAM_ID = 0",
           "  ) (",
           "    input addr[14],          // word address",
           "    output word[32]",
           "  ) {",
           "",
           "  always {",
           "    word = 0"]
    for name, (words, _) in assembled.items():
        out.append(f"    if (PROGRAM_ID == Programs.Id.{name} && addr < {len(image(words))}) "
                   f"word = Programs.{name}[addr];")
    out += ["  }", "}"]
    return "\n".join(out) + "\n"


def render_main_ram_v(assembled):
    out = [f"// {HEADER}",
           "// main_ram's hardware implementation: four byte lanes, one read port and one write port",
           "// (separate addresses), synchronous read with read-before-write (a read of the address being",
           "// written returns the old value). The initial block holds PROGRAM_ID's program (the",
           "// Programs.Id order in programs.luc); everything else starts at 0.",
           "module main_ram_bram #(",
           "    parameter PROGRAM_ID = 0,",
           "    parameter WORDS = 2048",
           "  ) (",
           "    input clk,",
           "    input [$clog2(WORDS)-1:0] raddr,",
           "    output reg [31:0] rdata,",
           "    input [$clog2(WORDS)-1:0] waddr,",
           "    input [31:0] wdata,",
           "    input [3:0] be",
           "  );",
           "",
           "  reg [7:0] lane0 [0:WORDS-1];",
           "  reg [7:0] lane1 [0:WORDS-1];",
           "  reg [7:0] lane2 [0:WORDS-1];",
           "  reg [7:0] lane3 [0:WORDS-1];",
           "",
           "  always @(posedge clk) begin",
           "    rdata <= {lane3[raddr], lane2[raddr], lane1[raddr], lane0[raddr]};",
           "    if (be[0]) lane0[waddr] <= wdata[7:0];",
           "    if (be[1]) lane1[waddr] <= wdata[15:8];",
           "    if (be[2]) lane2[waddr] <= wdata[23:16];",
           "    if (be[3]) lane3[waddr] <= wdata[31:24];",
           "  end",
           "",
           "  initial begin"]
    for pid, (name, (words, _)) in enumerate(assembled.items()):
        out.append(f"    if (PROGRAM_ID == {pid}) begin   // {name}")
        for i, w in enumerate(image(words)):
            if w:
                out.append(f"      lane0[{i}] = 8'h{w & 0xFF:02X}; lane1[{i}] = 8'h{(w >> 8) & 0xFF:02X}; "
                           f"lane2[{i}] = 8'h{(w >> 16) & 0xFF:02X}; lane3[{i}] = 8'h{w >> 24:02X};")
        out.append("    end")
    out += ["  end", "", "endmodule"]
    return "\n".join(out) + "\n"
