#!/usr/bin/env python3
"""Write the Zephyr devicetree include for the SoC from tools/memmap.py.

The addresses come from memmap.py (the one place they are defined), so the .dtsi cannot drift from
the hardware. What memmap.py does not hold (which interrupt line a device raises) is the table
below, from computer.luc / csr_file.luc: the UART receiver is platform line 0 (mie/mip bit 16), the
counter is platform line 1 (bit 17), the buttons are the external interrupt (11), the timer is 7.

  python3 tools/gen_dts.py            write zephyr/dts/riscv/riscitry/riscitry-memmap.dtsi
  python3 tools/gen_dts.py --check    exit 1 if that file is stale (no write)
"""
import os
import sys

import memmap as m

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "zephyr", "dts", "riscv",
                   "riscitry", "riscitry-memmap.dtsi")

IRQ_TIMER = 7        # machine timer interrupt (mie.MTIE)
IRQ_EXTERNAL = 11    # machine external interrupt (mie.MEIE): the buttons device
IRQ_UART_RX = 16     # platform line 0
IRQ_COUNTER = 17     # platform line 1


def hx(n):
    return f"0x{n:x}"


def render():
    ram_end = m.RAM_BASE + m.RAM_BYTES
    assert ram_end <= m.UART_BASE
    return f"""\
/* GENERATED by tools/gen_dts.py from tools/memmap.py. Do not edit; rerun the script.
 * Every address and size here is the hardware's (source/computer/computer.luc decodes the same map).
 * Included by riscitry.dtsi; the cpu0_intc label is defined there. */

/ {{
	ram: memory@{m.RAM_BASE:x} {{
		device_type = "memory";
		reg = <{hx(m.RAM_BASE)} {hx(m.RAM_BYTES)}>;
	}};

	soc {{
		#address-cells = <1>;
		#size-cells = <1>;
		compatible = "simple-bus";
		ranges;

		/* TXDATA +0, STATUS +4, RXDATA +8 (the read pops). RX interrupt = platform line 0. */
		uart0: serial@{m.UART_BASE:x} {{
			compatible = "riscitry,uart";
			reg = <{hx(m.UART_BASE)} {hx(m.UART_BYTES)}>;
			interrupts-extended = <&cpu0_intc {IRQ_UART_RX}>;
			status = "disabled";
		}};

		/* Read-only: the middle DIP bank, bits 7:0 (the boot menu's choice). */
		switches: switches@{m.SWITCHES_BASE:x} {{
			compatible = "riscitry,switches";
			reg = <{hx(m.SWITCHES_BASE)} {hx(m.SWITCHES_BYTES)}>;
		}};

		/* mtime +0, mtimecmp +8, both 64-bit, word access only. Ticks are 1 us on the board.
		 * (A read-only timebase word at +0x10 holds the clocks per tick.) */
		mtimer: timer@{m.TIMER_BASE:x} {{
			compatible = "riscv,machine-timer";
			reg = <{hx(m.TIMER_MTIME)} 0x8>, <{hx(m.TIMER_MTIMECMP)} 0x8>;
			reg-names = "mtime", "mtimecmp";
			interrupts-extended = <&cpu0_intc {IRQ_TIMER}>;
		}};

		/* Direction buttons: pending [3:0], overrun [7:4], levels [11:8]; the external interrupt. */
		buttons: buttons@{m.BUTTONS_BASE:x} {{
			compatible = "riscitry,buttons";
			reg = <{hx(m.BUTTONS_BASE)} {hx(m.BUTTONS_BYTES)}>;
			interrupts-extended = <&cpu0_intc {IRQ_EXTERNAL}>;
		}};

		/* Four characters, byte k = digit k from the left. */
		display: display@{m.DISPLAY_BASE:x} {{
			compatible = "riscitry,display";
			reg = <{hx(m.DISPLAY_BASE)} {hx(m.DISPLAY_BYTES)}>;
		}};

		/* CTRL +0, TOP +4, COUNT +8, STATUS +12. Overflow interrupt = platform line 1. */
		counter0: counter@{m.COUNTER_BASE:x} {{
			compatible = "riscitry,counter";
			reg = <{hx(m.COUNTER_BASE)} {hx(m.COUNTER_BYTES)}>;
			interrupts-extended = <&cpu0_intc {IRQ_COUNTER}>;
		}};

		/* 24 duty bytes at +0, CTRL at +0x18. */
		leds: led-dimmer@{m.LEDS_BASE:x} {{
			compatible = "riscitry,led-dimmer";
			reg = <{hx(m.LEDS_BASE)} {hx(m.LEDS_BYTES)}>;
		}};
	}};
}};
"""


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        try:
            current = open(OUT).read()
        except FileNotFoundError:
            current = None
        if current != text:
            sys.exit(f"{os.path.relpath(OUT)} is stale: rerun tools/gen_dts.py")
        print("gen_dts: up to date")
    else:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
        print("wrote", os.path.relpath(OUT))
